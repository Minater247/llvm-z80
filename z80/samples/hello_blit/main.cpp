class PRNG {
private:
    uint16_t state;

public:
    explicit PRNG(uint16_t seed = 1) : state(seed) {}

    uint16_t operator()() {
        state ^= state << 7;   // XOR with left-shifted state
        state ^= state >> 9;   // XOR with right-shifted state
        state ^= state << 8;   // XOR with left-shifted state again
        return state;
    }

    static uint16_t random_seed() {
        uint16_t iy = 0;
        __asm__ volatile(
            // frame counter
            "ld\tiy, (23672)"
            : "=iy"(iy)
        );
        return iy;
    }
};


int main() {
    ZX::Console::at(2, 10);
    ZX::Console::print("Press M for masked blitting.");
    ZX::Console::at(2, 11);
    ZX::Console::print("Press B for block blitting.");

    bool masked = false;
    while (true) {
        if (ZX::Keyboard::KEY_M.is_pressed()) {
            masked = true;
            break;
        }
        if (ZX::Keyboard::KEY_B.is_pressed())
            break;
    }
    PRNG rng(PRNG::random_seed());
    for (int i = 0; i < 1024; ) {
        uint8_t x = rng() & 0x1f;
        uint8_t y = rng() & 0x1f;
        if (masked) {
            if (x > 32 - SPRITE2.get_width() / 8)
                continue;
            if (y > 24 - SPRITE2.get_height() / 8)
                continue;
            SPRITE2.paint<ZX::Screen>(x, y);
        } else {
            if (x > 32 - SPRITE1.get_width() / 8)
                continue;
            if (y > 24 - SPRITE1.get_height() / 8)
                continue;
            SPRITE1.paint<ZX::Screen>(x, y);
        }
        ++i;
    }
    return 0;
}

